#!/usr/bin/env python3
"""Run only the reviewed refund fixture in three independent copies.

Records local JUnit observations, not trusted CI receipts or production acceptance.
Discovery inventories this fixture's DisplayName metadata, not arbitrary Java semantics.
"""
import argparse
import datetime
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'demo/refund-extraction'
MAIN = 'src/main/java/example/refunds/RefundService.java'
EXISTING = 'src/test/java/example/refunds/ExistingRefundContractTest.java'
PROPOSED = 'src/test/java/example/refunds/PartialRefundContractTest.java'
PROBE = '''package example.refunds;
import static org.junit.jupiter.api.Assertions.*;
import org.junit.jupiter.api.Test;
// Temporary candidate oracle generated by the reviewed fixture template.
class GeneratedRefundProbeTest {
    @Test void cumulativePartialRefundCounterexample() {
        var service = new RefundService(10000);
        assertDoesNotThrow(() -> service.refund("probe-1", 8000));
        assertThrows(IllegalArgumentException.class, () -> service.refund("probe-2", 3000));
        assertEquals(8000, service.refunded());
    }
}
'''
SPEC = importlib.util.spec_from_file_location('ci_formats', ROOT / 'scripts/ci-formats.py')
FORMATS = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(FORMATS)


def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()


def inventory(text):
    # Deliberately limited to reviewed fixture metadata. No inferred business truth.
    rows = []
    pattern = r'@DisplayName\("([^"\n]+)"\)\s+void\s+(\w+)\('
    for match in re.finditer(pattern, text):
        rows.append(dict(expectation=match[1], test_id='example.refunds.ExistingRefundContractTest.' + match[2],
                         source=EXISTING, line=text[:match.start()].count('\n') + 1,
                         source_sha256=digest(text), authority='candidate',
                         origin='existing_test_display_name',
                         limitation='Metadata observation; owner review and adversarial coverage required.'))
    if len(rows) != 4:
        raise ValueError('Reviewed fixture discovery inventory changed')
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--snapshot', type=Path, help='Optional public JSON snapshot, never a trusted receipt')
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    fixed = (SOURCE / MAIN).read_text()
    guard = 'if (amount <= 0 || amount > captured - refunded)'
    if fixed.count(guard) != 1:
        raise ValueError('Reviewed guard changed')
    sources = {
        'legacy': fixed.replace(guard, 'if (amount != captured) throw new IllegalArgumentException("Full refunds only");\n        ' + guard),
        'broken': fixed.replace(guard, 'if (amount <= 0 || amount > captured)'),
        'fixed': fixed,
    }
    environment = {key: value for key, value in os.environ.items()
                   if key in {'PATH', 'JAVA_HOME', 'HOME', 'TMPDIR', 'LANG', 'LC_ALL', 'SYSTEMROOT'}}
    variants, probes = {}, {}
    for name, code in sources.items():
        project = args.output / name
        shutil.copytree(SOURCE, project, ignore=shutil.ignore_patterns('target', '.git', '.env', '.env.*'))
        (project / MAIN).write_text(code)
        with (project / 'build-output.txt').open('wb') as log:
            run = subprocess.run(['mvn', '--offline', '--batch-mode', '--no-transfer-progress',
                                  '-f', str(project / 'pom.xml'), 'clean', 'test'],
                                 stdout=log, stderr=subprocess.STDOUT, env=environment, timeout=180)
        tests = []
        for path in sorted((project / 'target/surefire-reports').glob('TEST-*.xml')):
            tests.extend(FORMATS.junit(path.read_bytes()))
        expected = {}
        for method in ['rejectsRefundAboveCapture', 'rejectsASecondFullRefund',
                       'retryDoesNotRefundTwice', 'operationKeyCannotChangeAmount']:
            expected['example.refunds.ExistingRefundContractTest.' + method] = (
                'failed' if name == 'broken' and method == 'rejectsASecondFullRefund' else 'passed')
        for method in ['acceptsPartialRefund', 'partialRefundsShareOneBudget']:
            expected['example.refunds.PartialRefundContractTest.' + method] = (
                'failed' if name == 'legacy' or name == 'broken' and method == 'partialRefundsShareOneBudget' else 'passed')
        actual = {test['name']: test['status'] for test in tests}
        if len(tests) != 6 or actual != expected or (run.returncode == 0) != (name == 'fixed'):
            raise ValueError('Unexpected fixture execution: ' + name)
        variants[name] = dict(source=code, source_sha256=digest(code), tests=tests)
        if name != 'legacy':
            (project / 'src/test/java/example/refunds/GeneratedRefundProbeTest.java').write_text(PROBE)
            with (project / 'probe-output.txt').open('wb') as log:
                probe = subprocess.run(['mvn', '--offline', '--batch-mode', '--no-transfer-progress',
                                        '-f', str(project / 'pom.xml'),
                                        '-Dtest=GeneratedRefundProbeTest', 'test'],
                                       stdout=log, stderr=subprocess.STDOUT, env=environment, timeout=180)
            executions = FORMATS.junit((project / 'target/surefire-reports/TEST-example.refunds.GeneratedRefundProbeTest.xml').read_bytes())
            status = 'failed' if name == 'broken' else 'passed'
            if (len(executions) != 1 or executions[0]['status'] != status
                    or (probe.returncode == 0) != (name == 'fixed')):
                raise ValueError('Candidate probe did not reproduce expected assertion: ' + name)
            probes[name] = executions[0]
    tests = {path: (SOURCE / path).read_text() for path in [EXISTING, PROPOSED]}
    result = dict(schema_version=1, kind='recorded-local-junit', trusted_ci_import=False,
                  captured_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
                  assumptions='Sequential in-memory domain fixture. No HTTP service, provider, concurrent reservations, persistence, FX, or deployment.',
                  contracts=(SOURCE / 'contracts.json').read_text(),
                  proposed=(SOURCE / 'change-contracts.json').read_text(),
                  intent=(SOURCE / 'change-intent.md').read_text(),
                  cases=(SOURCE / 'cases.json').read_text(),
                  test_sources=tests, oracle_sha256=digest(''.join(tests.values())),
                  discovery=inventory(tests[EXISTING]), variants=variants,
                  probe=dict(source=PROBE, sha256=digest(PROBE), runs=probes,
                             authority='candidate', generator='reviewed_fixture_template'))
    content = json.dumps(result, indent=2) + '\n'
    (args.output / 'refund-fixture.json').write_text(content)
    if args.snapshot:
        args.snapshot.parent.mkdir(parents=True, exist_ok=True)
        args.snapshot.write_text(content)
    print('Refund fixture: 18 JUnit checks and 2 temporary probe executions matched; all observations retained.')


if __name__ == '__main__':
    main()
